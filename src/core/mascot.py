GOODBYE_SCALE = 3
GOODBYE_SIZE = 96


def _draw(runs, x, y, color, scale=1):
    for ry, rx, rw in runs:
        ssd.fill_rect(x + rx * scale, y + ry * scale,
                      rw * scale, scale, color)


def draw_spider(x, y, scale=1):
    _draw(SPIDER, x, y, AMBER, scale)


def draw_goodbye(x, y, scale=3):
    _draw(SPIDER, x, y, AMBER, scale)
